const root = document.documentElement;
const themeToggle = document.querySelector("#theme-toggle");
const status = document.querySelector("#preference-status");
let language = "en";

function remember(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    /* Preferences remain usable in memory. */
  }
}

function updateThemeButton() {
  const isLight = root.dataset.theme === "light";
  themeToggle.setAttribute(
    "aria-label",
    copy[language][isLight ? "darkTheme" : "lightTheme"],
  );
  themeToggle.setAttribute("aria-pressed", String(isLight));
  document.querySelector('meta[name="theme-color"]').content = isLight
    ? "#f4f4f0"
    : "#101216";
}

function setLanguage(next, announce = true) {
  language = next;
  root.lang = next;
  const text = copy[next];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = text[el.dataset.i18n];
    if (!value) return;
    // Keep line breaks without injecting HTML from translations.
    el.replaceChildren(
      ...value
        .split("\n")
        .flatMap((line, i) =>
          i
            ? [document.createElement("br"), document.createTextNode(line)]
            : [document.createTextNode(line)],
        ),
    );
  });
  document
    .querySelectorAll("[data-i18n-aria]")
    .forEach((el) => el.setAttribute("aria-label", text[el.dataset.i18nAria]));
  document
    .querySelectorAll("[data-i18n-alt]")
    .forEach((el) => (el.alt = text[el.dataset.i18nAlt]));
  document
    .querySelectorAll("[data-language]")
    .forEach((el) =>
      el.setAttribute("aria-pressed", String(el.dataset.language === next)),
    );
  document.title = text.pageTitle;
  document.querySelector('meta[name="description"]').content =
    text.pageDescription;
  document.querySelector('meta[property="og:title"]').content = text.pageTitle;
  document.querySelector('meta[property="og:description"]').content =
    text.ogDescription;
  document.querySelector('meta[property="og:locale"]').content =
    next === "en" ? "en_US" : "ru_RU";
  updateThemeButton();
  if (announce) status.textContent = text.languageChanged;
}

try {
  if (localStorage.getItem("puzo-language") === "ru") language = "ru";
} catch {
  /* English is the default. */
}
setLanguage(language, false);
document.querySelectorAll("[data-language]").forEach((button) =>
  button.addEventListener("click", () => {
    setLanguage(button.dataset.language);
    remember("puzo-language", language);
    updateMotionButton();
  }),
);
themeToggle.addEventListener("click", () => {
  const next = root.dataset.theme === "dark" ? "light" : "dark";
  root.dataset.theme = next;
  remember("puzo-theme", next);
  updateThemeButton();
  status.textContent =
    copy[language][next === "light" ? "themeLightStatus" : "themeDarkStatus"];
});
document.querySelector("#year").textContent = new Date().getFullYear();

const motionPreference = matchMedia("(prefers-reduced-motion: reduce)");
const motionToggle = document.querySelector("#motion-toggle");
let motionPaused = false;
try {
  motionPaused = localStorage.getItem("puzo-motion") === "paused";
} catch {}
function updateMotionButton() {
  const reduced = motionPreference.matches;
  const key = reduced
    ? "motionReduced"
    : motionPaused
      ? "motionResume"
      : "motionPause";
  motionToggle.setAttribute("aria-label", copy[language][key]);
  motionToggle.setAttribute("aria-pressed", String(motionPaused || reduced));
  motionToggle.disabled = reduced;
  motionToggle.querySelector(".motion-label").textContent =
    copy[language][key + "Label"];
  motionToggle.querySelector(".motion-icon").textContent =
    motionPaused || reduced ? "▷" : "Ⅱ";
}
function setMotionPaused(paused) {
  motionPaused = paused;
  root.classList.toggle("motion-paused", paused);
  updateMotionButton();
}
setMotionPaused(motionPaused);
motionToggle.addEventListener("click", () => {
  setMotionPaused(!motionPaused);
  remember("puzo-motion", motionPaused ? "paused" : "playing");
  status.textContent =
    motionToggle.getAttribute("aria-label") === copy[language].motionResume
      ? copy[language].motionPauseLabel
      : copy[language].motionResumeLabel;
});
const revealElements = document.querySelectorAll(".reveal");
let observer;
function configureMotion() {
  observer?.disconnect();
  updateMotionButton();
  root.classList.toggle("js-motion", !motionPreference.matches);
  if (!motionPreference.matches && "IntersectionObserver" in window) {
    observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add("visible");
            observer.unobserve(entry.target);
          }
        });
      },
      { threshold: 0.08 },
    );
    revealElements.forEach((el) => observer.observe(el));
  } else revealElements.forEach((el) => el.classList.add("visible"));
}
configureMotion();
motionPreference.addEventListener("change", configureMotion);

const heroArt = document.querySelector(".hero-art");
heroArt.addEventListener("pointermove", (event) => {
  if (motionPreference.matches || motionPaused || event.pointerType !== "mouse")
    return;
  const bounds = heroArt.getBoundingClientRect();
  heroArt.style.setProperty(
    "--pointer-x",
    `${(event.clientX - bounds.left - bounds.width / 2) * 0.035}px`,
  );
  heroArt.style.setProperty(
    "--pointer-y",
    `${(event.clientY - bounds.top - bounds.height / 2) * 0.035}px`,
  );
});
heroArt.addEventListener("pointerleave", () => {
  heroArt.style.setProperty("--pointer-x", "0px");
  heroArt.style.setProperty("--pointer-y", "0px");
});

const progress = document.querySelector(".scroll-progress");
let scrollQueued = false;
function updateProgress() {
  const range = document.documentElement.scrollHeight - innerHeight;
  progress.style.transform = `scaleX(${range > 0 ? scrollY / range : 0})`;
  scrollQueued = false;
}
addEventListener(
  "scroll",
  () => {
    if (!scrollQueued) {
      scrollQueued = true;
      requestAnimationFrame(updateProgress);
    }
  },
  { passive: true },
);
addEventListener("resize", updateProgress);
updateProgress();
